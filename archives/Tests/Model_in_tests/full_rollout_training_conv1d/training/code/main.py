# Entry point: composite-loss training of the Conv1d model (model.py) --
# every weight update combines THREE terms in one backward()+step():
#   - rollout: autoregressive TBPTT prediction error, chained hop by hop
#     over whole simulations, never reset to ground truth (train.py).
#   - physics: wave-equation residual (u_tt - (E/rho)*u_xx), computed for
#     free from the same tensors the rollout term already produces.
#   - data: plain one-step MSE on an independent batch drawn straight from
#     the flattened dataset (df/INPUTS/OUTPUTS), same mechanism this
#     project's dataloaders (training.make_dataloaders) always used.
# total = LAMBDA_ROLLOUT*rollout + LAMBDA_PHYSICS*physics + LAMBDA_DATA*data
# -- see config.py for the weights and train.train_full_rollout for the loop.
#
# Trains on trajectories pre-generated by Dataset/Creation_dataset.py and
# saved to one HDF5 file (dataset.load_hdf5_dataset), not on scenarios
# simulated on the fly -- that on-the-fly path (scenarios.py +
# dataset.generate_dataset_multisignal/split_by_simulation) still exists for
# standalone use (check_equivalence.py's free-evolution case still needs
# scenarios.sample_random_ic) but main.py itself no longer calls it.
